"""Scan the Planning Room's proposal folders for *_tools.json and update the tool index.

usage: python scan.py [--offline]

Reads every <proposals_dir>/20*/*_tools.json (read-only; config.json sets the path) and rebuilds index.json and INDEX.md.
- One entry per tool, keyed by its canonical GitHub repo: a renamed or moved repo redirects, so both URLs merge.
- "jobs" counts distinct Upwork jobs that listed the tool (two folders for the same job title count once).
  It decides the order videos are made in. Folder names and job titles are never stored.
- Video status and the "problem" line are kept between runs; everything else is recomputed.
- Canonical names are cached in index.json, so a re-scan only looks up repos it hasn't seen. --offline skips lookups.
"""
import collections, json, pathlib, re, sys, time, urllib.error, urllib.request

ROOT = pathlib.Path(__file__).parent
INDEX = ROOT / "index.json"
GH = re.compile(r"^https?://github\.com/([^/]+)/([^/?#]+)", re.I)
INTRO, HOWTO, COMPARE = "new", "not planned", "new"


def owner_repo(url):
    m = GH.match(url.strip())
    return f"{m.group(1)}/{m.group(2).removesuffix('.git')}" if m else None


def resolve(path):
    """Follow GitHub's redirect for a renamed or transferred repo; returns owner/repo, or None if the lookup failed."""
    req = urllib.request.Request(f"https://github.com/{path}", method="HEAD", headers={"User-Agent": "fix-found-scan"})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return owner_repo(r.geturl())
    except urllib.error.HTTPError as e:
        print(f"  lookup failed for {path}: HTTP {e.code}")
    except OSError as e:
        print(f"  lookup failed for {path}: {e}")
    return None


def main(offline):
    config = json.loads((ROOT / "config.json").read_text(encoding="utf-8"))
    proposals = (ROOT / config["proposals_dir"]).resolve()
    old = json.loads(INDEX.read_text(encoding="utf-8")) if INDEX.exists() else {}
    resolved = old.get("resolved", {})
    old_tools = {t["repo"].lower(): t for t in old.get("tools", [])}
    old_cats = {c["category"]: c for c in old.get("categories", [])}

    seen = collections.defaultdict(lambda: {"names": collections.Counter(), "cats": collections.Counter(), "jobs": set(), "first": "9999"})
    files = sorted(proposals.glob("20*/*_tools.json"))
    for f in files:
        job = re.sub(r"^\d{4}-\d{2}-\d{2}_proposal_for_|_by_jabran_khan_tools\.json$", "", f.name).lower()
        doc = json.loads(f.read_text(encoding="utf-8"))
        for t in doc["tools"]:
            path = owner_repo(t["repo"])
            if not path:
                print(f"  skipped a non-GitHub link in {f.parent.name}")
                continue
            if path.lower() not in resolved and not offline:
                canon = resolve(path)
                time.sleep(0.5)
                if canon:
                    resolved[path.lower()] = canon
            canon = resolved.get(path.lower(), path)
            s = seen[canon.lower()]
            s["repo"] = canon
            s["names"][t["name"]] += 1
            s["cats"][t["category"]] += 1
            s["jobs"].add(job)
            s["first"] = min(s["first"], doc.get("created", f.parent.name[:10]))

    tools = []
    for key, s in seen.items():
        prev = old_tools.get(key, {})
        tools.append({
            "name": s["names"].most_common(1)[0][0],
            "repo": s["repo"],
            "url": f"https://github.com/{s['repo']}",
            "category": s["cats"].most_common(1)[0][0],
            "jobs": len(s["jobs"]),
            "first_seen": s["first"],
            "problem": prev.get("problem", ""),
            "intro": prev.get("intro", INTRO),
            "howto": prev.get("howto", HOWTO),
        })
    tools.sort(key=lambda t: (-t["jobs"], t["first_seen"], t["name"].lower()))
    by_cat = collections.defaultdict(list)
    for t in tools:
        by_cat[t["category"]].append(t["name"])
    categories = [{"category": c, "tools": len(n), "compare": old_cats.get(c, {}).get("compare", COMPARE if len(n) >= 3 else "too few tools")}
                  for c, n in sorted(by_cat.items())]

    index = {"note": "Generated by scan.py. Edit only problem, intro, howto and compare by hand.",
             "updated": time.strftime("%Y-%m-%d"), "tools": tools, "categories": categories, "resolved": dict(sorted(resolved.items()))}
    INDEX.write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    md = [f"# Tool index\n", f"Generated by `scan.py` on {index['updated']} from {len(files)} proposals: "
          f"{len(tools)} tools in {len(categories)} categories. Ordered by how many jobs listed each tool.\n",
          "| # | Tool | Category | Jobs | Intro | How-to |", "|---|---|---|---|---|---|"]
    md += [f"| {i} | [{t['name']}]({t['url']}) | {t['category']} | {t['jobs']} | {t['intro']} | {t['howto']} |" for i, t in enumerate(tools, 1)]
    md += ["\n## Categories (comparison videos)\n", "| Category | Tools | Compare |", "|---|---|---|"]
    md += [f"| {c['category']} | {', '.join(by_cat[c['category']])} | {c['compare']} |" for c in categories]
    (ROOT / "INDEX.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    moved = {k: v for k, v in resolved.items() if k != v.lower()}
    print(f"{len(files)} proposals, {len(tools)} tools, {len(categories)} categories; {len(moved)} renamed repos merged")
    for k, v in moved.items():
        print(f"  {k} -> {v}")
    paths = {owner_repo(t["repo"]) for f in files for t in json.loads(f.read_text(encoding="utf-8"))["tools"]}
    unresolved = len({p.lower() for p in paths if p} - set(resolved))
    if unresolved and not offline:
        print(f"  {unresolved} repos couldn't be looked up; run again later")


if __name__ == "__main__":
    main("--offline" in sys.argv)
